let currentLocale = localStorage.getItem('bj.locale') || 'de';

function setLocale(loc) {
  currentLocale = STRINGS[loc] ? loc : 'de';
  localStorage.setItem('bj.locale', currentLocale);
  document.documentElement.lang = currentLocale;
}

function getLocale() {
  return currentLocale;
}

/** t('reports.rows', {n: 12}) */
function t(key, vars) {
  const dict = STRINGS[currentLocale] || STRINGS.de;
  let s = dict[key] ?? STRINGS.de[key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      s = s.replaceAll('{' + k + '}', v);
    }
  }
  return s;
}

/** Weather codes are grouped; fall back to the nearest documented code. */
function weatherText(code) {
  if (code === null || code === undefined) return '';
  const known = [0, 1, 2, 3, 45, 48, 51, 53, 55, 61, 63, 65, 71, 73, 75, 80, 81, 82, 95, 96, 99];
  let best = known[0];
  for (const c of known) if (c <= code) best = c;
  return t('wmo.' + best);
}
